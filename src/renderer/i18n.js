  // '' follows the system language (systemLocale), falling back to English.
  function setLanguage(lang, systemLocale = '') {
    const code = String(lang || systemLocale || 'en').toLowerCase().split(/[-_]/)[0];
    current = STRINGS[code] ? code : 'en';
    return current;
  }

  function t(key, vars = {}) {
    let text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
    if (typeof text === 'object') text = text[new Intl.PluralRules(current).select(vars.n)] ?? text.other;
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? vars[name] : match));
  }

